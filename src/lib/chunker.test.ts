function testTsFunctionSplit(): void {
  console.log("Test: TS function split")
  const file = makeFile("src/handler.ts", [
    "import { Router, Request, Response } from 'express'",
    "",
    "export async function getUser(req: Request, res: Response) {",
    "  const id = req.params.id",
    "  const user = await db.user.findUnique({ where: { id } })",
    "  if (!user) return res.status(404).json({ error: 'Not found' })",
    "  return res.json({ id: user.id, name: user.name })",
    "}",
    "",
    "export async function createUser(req: Request, res: Response) {",
    "  const body = req.body",
    "  const user = await db.user.create({ data: body })",
    "  if (!user) return res.status(500).json({ error: 'Create failed' })",
    "  return res.json({ created: true, id: user.id })",
    "}",
  ].join("\n"))
  const chunks = chunkFile(file, "test-repo", "api", "main", "abc123")
  assert(chunks.length >= 2, `Expected >=2 chunks, got ${chunks.length}`)
  const fn1 = chunks.find(c => c.symbolName === "getUser")
  assert(fn1 !== undefined, "getUser chunk should exist")
  assert(fn1!.chunkType === "function", `chunkType should be function, got ${fn1!.chunkType}`)
  assert(fn1!.content.includes("getUser"), "Content should include function name")
  const fn2 = chunks.find(c => c.symbolName === "createUser")
  assert(fn2 !== undefined, "createUser chunk should exist")
  console.log("  passed")
}

function testTsClassMethodSplit(): void {
  console.log("Test: TS class + method split")
  const file = makeFile("src/service.ts", [
    "export class UserService {",
    "  async findById(id: string) {",
    "    const user = await db.user.findUnique({ where: { id } })",
    "    if (!user) throw new NotFoundError('User not found')",
    "    return { id: user.id, name: user.name, email: user.email }",
    "  }",
    "",
    "  async create(data: CreateUserDto) {",
    "    const validated = await validateCreateUser(data)",
    "    const user = await db.user.create({ data: validated })",
    "    return { created: true, id: user.id, name: user.name }",
    "  }",
    "}",
  ].join("\n"))
  const chunks = chunkFile(file, "test-repo", "api", "main", "abc123")
  const methodChunks = chunks.filter(c => c.chunkType === "method")
  assert(methodChunks.length >= 2, `Expected >=2 methods, got ${methodChunks.length}`)
  assert(methodChunks.some(c => c.symbolName === "findById"), "findById method should exist")
  assert(methodChunks.some(c => c.symbolName === "create"), "create method should exist")
  methodChunks.forEach(c => assert(c.parentSymbol === "UserService", `parentSymbol should be UserService, got ${c.parentSymbol}`))
  console.log("  passed")
}

function testPhpFunctionSplit(): void {
  console.log("Test: PHP function split")
  const file = makeFile("src/handler.php", [
    "<?php",
    "function get_user($id) {",
    "  $db = new PDO($dsn, $user, $pass);",
    "  $stmt = $db->prepare('SELECT * FROM users WHERE id = :id');",
    "  $stmt->execute([':id' => $id]);",
    "  return $stmt->fetch(PDO::FETCH_ASSOC);",
    "}",
    "",
    "class UserController {",
    "  public function show($id) {",
    "    $user = $this->get_user($id);",
    "    if (!$user) {",
    "      http_response_code(404);",
    "      echo json_encode(['error' => 'User not found']);",
    "      return;",
    "    }",
    "    echo json_encode($user);",
    "  }",
    "}",
  ].join("\n"))
  const chunks = chunkFile(file, "test-repo", "api", "main", "abc123")
  const fnChunk = chunks.find(c => c.symbolName === "get_user")
  assert(fnChunk !== undefined, "get_user function chunk should exist")
  const methodChunk = chunks.find(c => c.chunkType === "method" && c.symbolName === "show")
  assert(methodChunk !== undefined, "show method chunk should exist")
  console.log("  passed")
}

