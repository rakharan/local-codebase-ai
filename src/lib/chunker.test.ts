function testFactsSkipComments(): void {
  console.log("Test: facts skip comment lines")
  const content = [
    "// This file was auto-generated from sdk-root/data.json",
    "const config = process.env.DB_HOST || 'localhost'",
    "/* SELECT * FROM users WHERE active = 1 */",
    "export const PORT = 3000",
  ].join("\n")
  const facts = extractStructuredFacts(content, 1)
  const commentFact = facts.find(f => f.text.trim().startsWith("//"))
  assert(commentFact === undefined, "Comment line should not produce a fact")
  const blockCommentFact = facts.find(f => f.text.trim().startsWith("/*"))
  assert(blockCommentFact === undefined, "Block comment line should not produce a fact")
  const envFact = facts.find(f => f.category === "config" && f.text.includes("process.env"))
  assert(envFact !== undefined, "process.env line should produce config fact")
  console.log("  passed")
}

function testCommentChunksFilterNoise(): void {
  console.log("Test: comment chunks filter noise")
  const content = [
    "<?php",
    "// This is a real comment about the function below",
    "// TODO: refactor this later",
    "function handler() { return true; }",
    "// #ffcc00",
    "// auto-generated by tool",
    "/* margin: 0; */",
    "",
    "/**",
    " * JSDoc: This function handles user authentication.",
    " * @param {string} token - JWT token",
    " */",
    "function auth(token) { return token }",
  ].join("\n")
  const chunks = createCommentChunks("test.php", content, "test-repo", "api", "main", "abc123")
  assert(chunks.length > 0, `Expected some comment chunks, got ${chunks.length}`)
  const cssNoise = chunks.find(c => /#ffcc00|margin:\s*0/i.test(c.content))
  assert(cssNoise === undefined, "CSS noise comment should be filtered")
  const autoGen = chunks.find(c => /auto-generated/i.test(c.content))
  assert(autoGen === undefined, "Auto-generated comment should be filtered")
  const jsdoc = chunks.find(c => /JSDoc|authentication/i.test(c.content))
  assert(jsdoc !== undefined, "JSDoc comment should survive")
  const todo = chunks.find(c => /TODO/i.test(c.content))
  assert(todo !== undefined, "TODO comment should survive")
  console.log("  passed")
}

